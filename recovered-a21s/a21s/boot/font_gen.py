#!/usr/bin/env python3
# Generates font.h: 8x16 bitmap glyphs for ASCII 32..126 from a monospace TTF (host-side tool).
import sys
from PIL import Image, ImageDraw, ImageFont
path = sys.argv[1] if len(sys.argv) > 1 else "/System/Library/Fonts/Menlo.ttc"
font = ImageFont.truetype(path, 13, index=0)
out = ["/* generated by font_gen.py: 8x16 glyphs, ASCII 32..126, MSB = leftmost pixel */",
       "static const unsigned char font8x16[95][16] = {"]
for c in range(32, 127):
    im = Image.new("L", (8, 16), 0)
    d = ImageDraw.Draw(im)
    bb = d.textbbox((0, 0), "M", font=font)
    d.text((0 if bb[0] >= 0 else -bb[0], 0), chr(c), fill=255, font=font)
    rows = []
    for y in range(16):
        v = 0
        for x in range(8):
            if im.getpixel((x, y)) > 110:
                v |= 0x80 >> x
        rows.append(v)
    out.append("  {" + ",".join("0x%02x" % r for r in rows) + "}, /* '%s' */" % (chr(c) if chr(c) not in "\\*/'" else "?"))
out.append("};")
open("font.h", "w").write("\n".join(out) + "\n")
